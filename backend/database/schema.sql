CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(30) NOT NULL, password VARCHAR(255) NOT NULL, birth_date DATE NOT NULL,
 role ENUM('customer','admin','staff') NOT NULL DEFAULT 'customer', age_status ENUM('belum','menunggu','disetujui','ditolak') DEFAULT 'belum',
 ktp_image VARCHAR(255), token_version INT NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS addresses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, label VARCHAR(60) NOT NULL,
 recipient VARCHAR(120) NOT NULL, phone VARCHAR(30) NOT NULL, address TEXT NOT NULL, city VARCHAR(120) NOT NULL,
 province VARCHAR(120) NOT NULL, postal_code VARCHAR(10) NOT NULL, is_default BOOLEAN DEFAULT FALSE,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, slug VARCHAR(100) UNIQUE NOT NULL,
 is_age_restricted BOOLEAN DEFAULT FALSE, is_active BOOLEAN DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id BIGINT UNSIGNED NOT NULL, name VARCHAR(190) NOT NULL,
 slug VARCHAR(190) UNIQUE NOT NULL, description TEXT NOT NULL, price DECIMAL(14,0) NOT NULL, stock INT UNSIGNED DEFAULT 0,
 weight_gram INT UNSIGNED DEFAULT 500, is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_variants (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, name VARCHAR(100) NOT NULL,
 sku VARCHAR(100) UNIQUE NOT NULL, price_override DECIMAL(14,0), stock INT UNSIGNED DEFAULT 0,
 FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS product_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, image_url VARCHAR(500) NOT NULL,
 sort_order INT DEFAULT 0, FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS carts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED UNIQUE NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cart_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cart_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL, qty INT UNSIGNED NOT NULL,
 UNIQUE KEY cart_variant(cart_id,variant_id), FOREIGN KEY (cart_id) REFERENCES carts(id) ON DELETE CASCADE,
 FOREIGN KEY (product_id) REFERENCES products(id), FOREIGN KEY (variant_id) REFERENCES product_variants(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_number VARCHAR(60) UNIQUE NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 address_snapshot JSON NOT NULL, subtotal DECIMAL(14,0) NOT NULL, shipping_cost DECIMAL(14,0) NOT NULL,
 total DECIMAL(14,0) NOT NULL, status VARCHAR(40) NOT NULL DEFAULT 'menunggu_pembayaran', payment_proof VARCHAR(255),
 courier VARCHAR(100) NOT NULL, tracking_number VARCHAR(100), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 expires_at DATETIME NOT NULL, FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL, name_snapshot VARCHAR(255) NOT NULL, price DECIMAL(14,0) NOT NULL, qty INT UNSIGNED NOT NULL,
 FOREIGN KEY (order_id) REFERENCES orders(id), FOREIGN KEY (product_id) REFERENCES products(id), FOREIGN KEY (variant_id) REFERENCES product_variants(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED UNIQUE NOT NULL, method VARCHAR(30) DEFAULT 'transfer',
 amount DECIMAL(14,0) NOT NULL, proof_image VARCHAR(255), status VARCHAR(30) DEFAULT 'menunggu',
 verified_by BIGINT UNSIGNED, verified_at DATETIME, FOREIGN KEY (order_id) REFERENCES orders(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS banners (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, image_url VARCHAR(500) NOT NULL, link VARCHAR(500), is_active BOOLEAN DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (`key` VARCHAR(100) PRIMARY KEY, value TEXT NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS rate_limits (bucket VARCHAR(100) PRIMARY KEY, attempts INT NOT NULL DEFAULT 1, window_start INT NOT NULL) ENGINE=InnoDB;
CREATE INDEX orders_user_status ON orders(user_id,status);
CREATE INDEX products_category_active ON products(category_id,is_active);
